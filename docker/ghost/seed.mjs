#!/usr/bin/env node
// Idempotent local Ghost bootstrap for the dev log + comics content (docs/ghost.md).
//
// 1. Runs Ghost's first-time owner setup (skipped when already set up).
// 2. Signs in as the owner and creates (or reuses) the "NYCU LIFE landing build"
//    Custom Integration, then writes its Content + Admin API keys to the untracked
//    `.env.ghost.local` at the repo root (with the owner credentials, so re-runs
//    need no env).
// 3. Uploads generated SVG covers/panels and creates the 10 sample episodes,
//    tagged `#comics` + `#ep-NN` (existing slugs are left untouched).
// 4. Creates sample dev log posts tagged `#devlog` (existing slugs untouched).
//    Set GHOST_SEED_COMICS=0 to skip step 3 (e.g. to preview "no comics yet").
//
// No dependencies; Node 24+. Environment:
//   GHOST_ADMIN_URL      default http://127.0.0.1:2368
//   GHOST_OWNER_EMAIL    default editor@nycu.life.local
//   GHOST_OWNER_PASSWORD required on first run (Ghost requires 10+ chars); later
//                        runs read it back from GHOST_ENV_FILE
//   GHOST_OWNER_NAME     default NYCU LIFE Editor
//   GHOST_ENV_FILE       default <repo>/.env.ghost.local
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const envFile = process.env.GHOST_ENV_FILE ?? resolve(repoRoot, '.env.ghost.local');

// Re-runs read the owner credentials saved by the first run (explicit env wins).
try {
	for (const line of (await readFile(envFile, 'utf8')).split('\n')) {
		const match = /^(GHOST_OWNER_EMAIL|GHOST_OWNER_PASSWORD)=(.*)$/.exec(line);
		if (match && !process.env[match[1]]) process.env[match[1]] = match[2];
	}
} catch {
	// First run: no env file yet.
}
const adminUrl = (process.env.GHOST_ADMIN_URL ?? 'http://127.0.0.1:2368').replace(/\/+$/, '');
const email = process.env.GHOST_OWNER_EMAIL ?? 'editor@nycu.life.local';
const password = process.env.GHOST_OWNER_PASSWORD ?? '';
const ownerName = process.env.GHOST_OWNER_NAME ?? 'NYCU LIFE Editor';
const integrationName = 'NYCU LIFE landing build';
const api = `${adminUrl}/ghost/api/admin`;
const origin = new URL(adminUrl).origin;

let cookie = '';

async function request(method, path, { json, form, allow = [] } = {}) {
	const headers = { 'Accept-Version': 'v6.0', Origin: origin };
	if (cookie) headers.Cookie = cookie;
	let body;
	if (json !== undefined) {
		headers['Content-Type'] = 'application/json';
		body = JSON.stringify(json);
	} else if (form) {
		body = form;
	}
	const response = await fetch(`${api}${path}`, { method, headers, body });
	const setCookie = response.headers.getSetCookie?.() ?? [];
	if (setCookie.length) cookie = setCookie.map((value) => value.split(';')[0]).join('; ');
	const text = await response.text();
	let data;
	try {
		data = text ? JSON.parse(text) : {};
	} catch {
		data = { text }; // e.g. POST /session/ answers a plain "Created"
	}
	if (!response.ok && !allow.includes(response.status)) {
		const detail = data.errors?.map(
			(error) => error.message + (error.context ? ` (${error.context})` : '')
		);
		throw new Error(`${method} ${path} → ${response.status}: ${detail?.join('; ') ?? text}`);
	}
	return { status: response.status, data };
}

async function waitForGhost() {
	for (let attempt = 0; attempt < 60; attempt += 1) {
		try {
			const response = await fetch(`${api}/site/`, { headers: { 'Accept-Version': 'v6.0' } });
			if (response.ok) return;
		} catch {
			// Ghost still booting.
		}
		await new Promise((done) => setTimeout(done, 2000));
	}
	throw new Error(`Ghost did not answer at ${adminUrl}`);
}

async function ensureOwner() {
	const { data } = await request('GET', '/authentication/setup/');
	if (data.setup?.[0]?.status) {
		console.log('• Ghost owner already set up');
		return;
	}
	if (password.length < 10) {
		throw new Error('Set GHOST_OWNER_PASSWORD (10+ characters) for the first-time owner setup.');
	}
	await request('POST', '/authentication/setup/', {
		json: { setup: [{ name: ownerName, email, password, blogTitle: 'NYCU LIFE CMS' }] }
	});
	// Save the credentials before anything else can fail.
	await writeEnvFile();
	console.log(`• Created Ghost owner ${email} (credentials in ${envFile})`);
}

async function signIn() {
	if (!password) throw new Error('Set GHOST_OWNER_PASSWORD to sign in as the Ghost owner.');
	await request('POST', '/session/', { json: { username: email, password } });
}

async function writeEnvFile(keys = {}) {
	await writeFile(
		envFile,
		[
			'# Generated by docker/ghost/seed.mjs — local only, never commit.',
			`GHOST_URL=${adminUrl}`,
			...Object.entries(keys).map(([name, value]) => `${name}=${value}`),
			`GHOST_OWNER_EMAIL=${email}`,
			`GHOST_OWNER_PASSWORD=${password}`,
			''
		].join('\n'),
		{ mode: 0o600 }
	);
}

async function ensureIntegration() {
	const { data } = await request('GET', '/integrations/?include=api_keys&limit=all');
	let integration = data.integrations.find((item) => item.name === integrationName);
	if (!integration) {
		const created = await request('POST', '/integrations/?include=api_keys', {
			json: {
				integrations: [
					{
						name: integrationName,
						description: 'Build-time Content API access for nycu.life (dev log, comics).'
					}
				]
			}
		});
		integration = created.data.integrations[0];
		console.log(`• Created Custom Integration "${integrationName}"`);
	} else {
		console.log(`• Reusing Custom Integration "${integrationName}"`);
	}
	const contentKey = integration.api_keys.find((key) => key.type === 'content').secret;
	const adminKey = integration.api_keys.find((key) => key.type === 'admin');
	await writeEnvFile({
		GHOST_CONTENT_API_KEY: contentKey,
		GHOST_ADMIN_API_KEY: `${adminKey.id}:${adminKey.secret}`
	});
	console.log(`• Wrote API keys to ${envFile}`);
}

