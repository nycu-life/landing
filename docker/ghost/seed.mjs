const escapeXml = (value) =>
	value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function coverSvg(n, title) {
	const ep = String(n).padStart(2, '0');
	return `<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080" viewBox="0 0 1080 1080">
<rect width="1080" height="1080" fill="#e3ebff"/>
<circle cx="840" cy="240" r="380" fill="#ccdbff"/>
<circle cx="200" cy="860" r="90" fill="#4d7fff"/>
<text x="540" y="560" text-anchor="middle" font-family="Ubuntu, 'Noto Sans TC', sans-serif" font-size="170" font-weight="700" fill="#0045f2">EP.${ep}</text>
<text x="540" y="660" text-anchor="middle" font-family="'Noto Sans TC', sans-serif" font-size="56" font-weight="700" fill="#0b1f5c">${escapeXml(title)}</text>
<text x="540" y="1010" text-anchor="middle" font-family="sans-serif" font-size="32" fill="#2455a8">Ghost seed · sample cover</text>
</svg>`;
}

function panelSvg(n, panel) {
	const hues = ['#fff4d6', '#e6f7ef', '#fde8ef'];
	return `<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1350" viewBox="0 0 1080 1350">
<rect width="1080" height="1350" fill="${hues[(panel - 1) % hues.length]}"/>
<rect x="40" y="40" width="1000" height="1270" rx="28" fill="none" stroke="#0b1f5c" stroke-width="10"/>
<circle cx="540" cy="600" r="220" fill="#4d7fff" opacity="0.85"/>
<rect x="140" y="980" width="800" height="200" rx="40" fill="#ffffff" stroke="#0b1f5c" stroke-width="6"/>
<text x="540" y="1100" text-anchor="middle" font-family="'Noto Sans TC', sans-serif" font-size="64" font-weight="700" fill="#0b1f5c">第 ${n} 集 · 第 ${panel} 格</text>
<text x="540" y="140" text-anchor="middle" font-family="sans-serif" font-size="40" fill="#2455a8">sample panel ${panel}/3</text>
</svg>`;
}

async function upload(name, svg) {
	const form = new FormData();
	form.append('file', new Blob([svg], { type: 'image/svg+xml' }), name);
	form.append('purpose', 'image');
	form.append('ref', name);
	const { data } = await request('POST', '/images/upload/', { form });
	return data.images[0].url;
}

async function ensureEpisodes() {
	const firstPublished = Date.parse('2026-09-01T09:00:00+08:00');
	for (const [index, title] of TITLES.entries()) {
		const n = index + 1;
		const ep = String(n).padStart(2, '0');
		const slug = `ep-${ep}`;
		const existing = await request('GET', `/posts/slug/${slug}/`, { allow: [404] });
		if (existing.status === 200) {
			console.log(`• ${slug} exists, skipping`);
			continue;
		}
		const cover = await upload(`comic-${slug}-cover.svg`, coverSvg(n, title));
		const panels = [];
		for (const panel of [1, 2, 3]) {
			panels.push(await upload(`comic-${slug}-panel-${panel}.svg`, panelSvg(n, panel)));
		}
		const html = [
			`<p>（範例內容）第 ${n} 集：${escapeXml(title)}。</p>`,
			...panels.map(
				(src, i) =>
					`<figure class="kg-card kg-image-card"><img src="${src}" class="kg-image" alt="第 ${n} 集第 ${i + 1} 格" width="1080" height="1350"></figure>`
			)
		].join('\n');
		await request('POST', '/posts/?source=html', {
			json: {
				posts: [
					{
						title,
						slug,
						html,
						status: 'published',
						published_at: new Date(firstPublished + index * 7 * 86_400_000).toISOString(),
						feature_image: cover,
						feature_image_alt: `EP.${ep} ${title}`,
						custom_excerpt: `小貢的校園日常第 ${n} 集（Ghost 範例內容）。`,
						tags: [{ name: '#comics' }, { name: `#ep-${ep}` }]
					}
				]
			}
		});
		console.log(`• Created ${slug} ${title}`);
	}
}

